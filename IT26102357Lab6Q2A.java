public class IT26102357Lab6Q2A {
    public static void main(String[] args) {
        int count = 1;

        // Print numbers 1 through 10 on the same line separated by spaces
        while (count <= 10) {
            System.out.print(count + " ");
            count++;
        }
        System.out.println(); // New line at the end
    }
}